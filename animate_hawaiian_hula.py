"""Add a smooth, editable eight-second 60 fps hula loop to the approved v2 plush.
Run: blender -b hello_kitty_hawaiian_plush_v2.blend --threads 4 --python-exit-code 1 --python animate_hawaiian_hula.py
Set KITTY_HULA_OUTPUT_DIR to choose an output directory. Add -- --preview for a rendered still.
"""
import bpy,math,os,sys
from pathlib import Path
from mathutils import Vector
from math import sin,cos,pi
OUT=Path(os.environ.get('KITTY_HULA_OUTPUT_DIR',str(Path(bpy.data.filepath).parent/'hawaiian_hula')))
OUT.mkdir(parents=True,exist_ok=True)
s=bpy.context.scene
assert bpy.data.objects.get('Plush head') and bpy.data.objects.get('Hula felt panel 00'), 'Load the approved Hawaiian plush v2 scene first.'
assert not bpy.data.objects.get('CTRL_Skirt_00'), 'Load the static v2 model to rebuild the dance.'
body=bpy.data.objects['CTRL_Body'];head=bpy.data.objects['CTRL_Head'];root=bpy.data.objects['CTRL_Root']
control_collection=bpy.data.collections['CONTROLS']
for o in bpy.data.objects:
    if o.animation_data:o.animation_data_clear()

def preserve_parent(o,p):
    bpy.context.view_layer.update();w=o.matrix_world.copy();o.parent=p;o.matrix_world=w

def move_pivot(ctrl,point):
    bpy.context.view_layer.update();children=[(o,o.matrix_world.copy()) for o in ctrl.children]
    w=ctrl.matrix_world.copy();w.translation=Vector(point);ctrl.matrix_world=w
    bpy.context.view_layer.update()
    for o,m in children:o.matrix_world=m
    bpy.context.view_layer.update()
# Reposition the paw controls to the shoulders, keeping their stuffed geometry.
move_pivot(bpy.data.objects['CTRL_Paw_L'],(-.70,-.14,2.13))
move_pivot(bpy.data.objects['CTRL_Paw_R'],(.70,-.10,2.05))
# Each skirt panel swings from its sewn waist edge, never from the ground origin.
skirt=[]
for i in range(17):
    panel=bpy.data.objects[f'Hula felt panel {i:02d}']
    top=sum((panel.matrix_world@v.co for v in list(panel.data.vertices)[:5]),Vector())/5
    ctrl=bpy.data.objects.new(f'CTRL_Skirt_{i:02d}',None);control_collection.objects.link(ctrl)
    ctrl.location=top;ctrl.empty_display_type='PLAIN_AXES';ctrl.empty_display_size=.08
    preserve_parent(ctrl,body);preserve_parent(panel,ctrl);skirt.append(ctrl)
# Cubic Hermite handles retain both the pose and velocity at the loop seam.
# All frames are generated by Blender's animation curves, including subframes.
PERIOD=480;STEP=10

def animate(o,channels):
    for prop,fn in channels.items():
        for f in range(1,PERIOD+2,STEP):
            setattr(o,prop,fn((f-1)/PERIOD));o.keyframe_insert(prop,frame=f,group='Hula — '+o.name)
    action=o.animation_data.action;action.name=o.name+' — Hula 8s continuous loop'
    for c in action.fcurves:
        fn=channels[c.data_path];i=c.array_index
        for k in c.keyframe_points:
            f=k.co.x;u=(f-1)/PERIOD;eps=1e-5
            slope=(fn(u+eps)[i]-fn(u-eps)[i])/(2*eps*PERIOD)
            k.interpolation='BEZIER';k.handle_left_type=k.handle_right_type='FREE'
            k.handle_left=(f-STEP/3,k.co.y-slope*STEP/3)
            k.handle_right=(f+STEP/3,k.co.y+slope*STEP/3)
        c.modifiers.new('CYCLES');c.update()

def hip(u):return 8*pi*u

def gesture(u):return 4*pi*u

b=body.location.copy();scale=body.scale.copy()
animate(body,{
 'location':lambda u:(b.x+.13*sin(hip(u)),b.y,b.z-.035*(1-cos(2*hip(u)))),
 'rotation_euler':lambda u:(.025*sin(hip(u)+.25),.060*sin(hip(u)),.075*sin(hip(u)-.15)),
 'scale':lambda u:(scale.x,scale.y,scale.z*(1-.0175*(1-cos(2*hip(u)))))})
animate(head,{'rotation_euler':lambda u:(.020*sin(gesture(u)-.3),-.045*sin(hip(u)-.25),-.035*sin(hip(u)-.2))})
for side in ['L','R']:
    ctrl=bpy.data.objects['CTRL_Paw_'+side]
    baseline=-1.10 if side=='L' else .10
    direction=-1 if side=='L' else 1
    animate(ctrl,{'rotation_euler':lambda u,base=baseline,d=direction:(.10*cos(gesture(u)+d*.25),base+.38*sin(gesture(u)),d*.12*cos(gesture(u)-.35))})
for i,ctrl in enumerate(skirt):
    angle=2*pi*i/17
    animate(ctrl,{'rotation_euler':lambda u,a=angle:(.035*sin(hip(u)-.7+a),-.11*sin(hip(u)-.60)+.022*sin(2*hip(u)+a),.022*cos(hip(u)-.5+a))})
s.frame_start=1;s.frame_end=480;s.render.fps=60;s.render.fps_base=1
s.render.use_motion_blur=True;s.render.motion_blur_shutter=.30;s.eevee.motion_blur_steps=1
s.render.resolution_x=1080;s.render.resolution_y=1350;s.render.resolution_percentage=100
s.eevee.taa_render_samples=32
s.render.filepath='//hula_frames/frame_';s.render.image_settings.file_format='PNG'
s.sync_mode='FRAME_DROP'
# Keep the detailed pile in final renders while making timeline playback lighter.
fibers=bpy.data.collections.get('FIBERS — short plush pile')
if fibers:
    fibers.hide_viewport=True
    fibers.hide_render=False
s.timeline_markers.clear()
for name,frame in [('Hula — sway left',1),('Flowing paws — sweep',61),('Hula — sway right',121),('Paws return',181),('Repeat phrase',241),('Final sway',421),('Loop seam (next cycle)',481)]:s.timeline_markers.new(name,frame=frame)
s['Animation notes']='Eight-second hula loop: 60 fps, frames 1–480; frame 481 matches frame 1 and its velocity. Hip sways, gentle knee compression, shoulder-driven paw gestures, counterbalanced head and independently swaying skirt panels. Feet stay planted.'
s['Controls']='Animated hula: CTRL_Body, CTRL_Head, CTRL_Paw_L/R and CTRL_Skirt_*; 8 seconds at 60 fps.'
t=bpy.data.texts.get('START HERE') or bpy.data.texts.new('START HERE');t.clear();t.write('HAWAIIAN PLUSH — HULA DANCE\n\nBlender 4.3+. Space plays the eight-second, 60 fps loop on frames 1–480.\nUse Solid or Material viewport shading and hide FIBERS for faster playback. The viewport may drop frames on slower computers; animation curves retain the full 60 fps timing.\nCTRL_Body: hips and knee compression. CTRL_Head: counterbalance. CTRL_Paw_L/R: shoulder pivots. CTRL_Skirt_*: delayed felt-panel swing. Curves are editable in the Graph Editor.\nFrame 481 is the matching loop endpoint and is excluded from export.\nF12 renders a still. Ctrl-F12 renders the full PNG sequence into hula_frames/ beside this file.\nResolution: 1080 x 1350; subtle motion blur enabled. No add-ons or external assets.\nThis is a stylized plush object-control dance rig, not a deforming skeletal rig.\n')
t.write('\nThe detailed FIBERS collection is hidden in the viewport by default for smoother playback. Enable its monitor icon to inspect the pile; final renders include it automatically.\n')
# Verify continuity on the actual object hierarchy and that feet remain planted.
controls=[body,head,*[bpy.data.objects['CTRL_Paw_'+v] for v in ['L','R']],*skirt]
s.frame_set(1);start={o.name:o.matrix_world.copy() for o in controls}
feet=[bpy.data.objects['Plush foot '+str(i)] for i in [-1,1]]
foot_start={o.name:o.matrix_world.copy() for o in feet}
s.frame_set(481)
assert max(abs(start[o.name][i][j]-o.matrix_world[i][j]) for o in controls for i in range(4) for j in range(4))<1e-4
for f in [31,91,151,211,271,331,391,451]:
    s.frame_set(f)
    assert max(abs(foot_start[o.name][i][j]-o.matrix_world[i][j]) for o in feet for i in range(4) for j in range(4))<1e-6
s.frame_set(1)
bpy.context.preferences.filepaths.save_version=0
bpy.ops.wm.save_as_mainfile(filepath=str(OUT/'hello_kitty_hawaiian_hula.blend'))
print('HULA_VALIDATED: continuous eight-second loop, planted feet, shoulder controls and 17 skirt pivots',flush=True)
if '--preview' in sys.argv:
    s.frame_set(61);s.render.filepath=str(OUT/'hawaiian_hula_preview.png')
    if '--draft' in sys.argv:s.render.resolution_percentage=60;s.eevee.taa_render_samples=8
    bpy.ops.render.render(write_still=True)
